function ref(id: string, role: "primary" | "feature" | "group" = "primary") {
  const found = ARTISTS.find((a) => a.id === id);
  if (!found) throw new Error(`Missing artist ${id}`);
  return { id, name: found.name, role };
}

function track(
  partial: Omit<Track, "normalizedTitle" | "country" | "genre" | "artists"> & {
    artists: Track["artists"];
  },
): Track {
  return {
    ...partial,
    normalizedTitle: normalizeText(partial.title),
    country: "IN",
    genre: "DHH",
  };
}

