import { normalizeText } from "../normalize";

function artist(
  id: string,
  name: string,
  aliases: string[],
  tags: string[] = [],
): Artist {
  return {
    id,
    name,
    normalizedName: normalizeText(name),
    aliases,
    country: "IN",
    sceneTags: tags,
    active: true,
  };
}

